const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync('index.html', 'utf8');
const start = html.indexOf('function constrainedMove(');
const end = html.indexOf('\nfunction continueCanvasDrag(', start);
const context = vm.createContext({Math, snapValue: n => Math.round(n / 8) * 8});
vm.runInContext(html.slice(start, end), context);
const drag = () => ({dx: 5, dy: 5, originX: 13, originY: 19, startX: 18, startY: 24, axis: null});
let d = drag();
let p = context.constrainedMove(d, {x: 19, y: 25}, true);
assert.equal(p.x, 13); assert.equal(p.y, 19);
p = context.constrainedMove(d, {x: 22, y: 50}, true);
assert.equal(d.axis, 'y'); assert.equal(p.x, 13); assert.equal(p.y, 48);
p = context.constrainedMove(d, {x: 100, y: 60}, true);
assert.equal(p.x, 13); assert.equal(p.y, 56);
p = context.constrainedMove(d, {x: 100, y: 60}, false);
assert.equal(d.axis, null); assert.equal(p.x, 96); assert.equal(p.y, 56);
d = drag();
p = context.constrainedMove(d, {x: 50, y: 28}, true);
assert.equal(d.axis, 'x'); assert.equal(p.x, 48); assert.equal(p.y, 19);
p = context.constrainedMove(d, {x: 0, y: 100}, true);
assert.equal(p.y, 19);
console.log('Shift axis locking, dead zone, snapping and free movement passed.');
